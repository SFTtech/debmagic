/// Reserved desktop categories. They need OnlyShowIn.
pub(super) const RESERVED_CATEGORIES: &[&str] = &["Screensaver", "TrayIcon", "Applet", "Shell"];

/// Desktop entry types this check validates.
pub(super) const DESKTOP_TYPES: &[&str] = &["Application", "Link", "Directory"];

pub(super) fn contains(table: &[&str], key: &str) -> bool {
    table.contains(&key)
}

pub(super) fn menu_root_known(root: &str) -> bool {
    MENU_SECTIONS.iter().any(|(name, _)| *name == root)
}

pub(super) fn menu_under_known(root: &str, under: &str) -> bool {
    MENU_SECTIONS
        .iter()
        .any(|(name, child)| *name == root && *child == under)
}
