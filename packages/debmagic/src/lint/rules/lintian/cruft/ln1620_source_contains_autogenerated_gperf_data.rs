use std::sync::LazyLock;

use crate::declare_rule;
use crate::lint::context::SourceContext;
use crate::lint::diagnostic::{Diagnostic, Location};
use crate::lint::license_text::{self, BadLicense};
use crate::lint::rule::{Severity, SourceRule};

pub struct SourceContainsAutogeneratedGperfData;

declare_rule! {
    /// A Patched file is C or C++ code that gperf generated: its text says
    /// `code produced by gperf version N.N`. Reported at pedantic severity
    /// with an empty extra and the path as the Location, the pointer form
    /// lintian's `cruft` Check emits.
    ///
    /// The file's cleaned text is matched as lintian's `cruft` Check does: a
    /// keyword, the sentence and the regex. Skipped in a non-free Source
    /// package (see `license_text::is_non_free`), and paths under `.pc/` are
    /// skipped.
    ///
    /// Differs from lintian: the file is matched whole, not in 16 KiB
    /// sliding-window blocks.
    SourceContainsAutogeneratedGperfData,
    code = "LN1620",
    tag = "source-contains-autogenerated-gperf-data",
    default_selected = false,
    experimental = false,
}

static GPERF: LazyLock<BadLicense> = LazyLock::new(|| {
    BadLicense::new(
        &["code", "produced", "gperf", "version"],
        &["code produced by gperf version"],
        Some(r"code [ ] produced [ ] by [ ] gperf [ ] version [ ] \d+\.\d+"),
    )
});

impl SourceRule for SourceContainsAutogeneratedGperfData {
    fn run(&self, ctx: &mut SourceContext<'_>) {
        if license_text::is_non_free(ctx) {
            return;
        }
        let texts = license_text::shared_text_files(ctx);
        let flagged: Vec<_> = texts
            .iter()
            .filter(|file| GPERF.matches(file))
            .map(|file| file.path.clone())
            .collect();
        for path in flagged {
            ctx.diagnostic(
                Diagnostic::warn("")
                    .with_severity(Severity::Pedantic)
                    .with_location(Location {
                        path,
                        line: None,
                        column: None,
                    }),
            );
        }
    }
}

#[cfg(test)]
mod tests {
    use crate::lint::tester::{SourcePackageCase, SourcePackageTester, SourceTreeTester, TestFile};

    use super::*;

    const CONTROL: &str = "Source: example\n\
         Maintainer: Example <ex@example.com>\n\
         Standards-Version: 4.7.2\n\
         \n\
         Package: example\n\
         Architecture: all\n\
         Description: example\n extra\n";

    const NON_FREE_CONTROL: &str = "Source: example\n\
         Section: non-free/libs\n\
         Maintainer: Example <ex@example.com>\n\
         Standards-Version: 4.7.2\n\
         \n\
         Package: example\n\
         Architecture: all\n\
         Description: example\n extra\n";

    const GPERF: &str = "/* C++ code produced by gperf version 3.1 */\n\
         /* Command-line: gperf keywords.gperf */\n\
         int main() {}\n";

    #[test]
    fn test() {
        let pass = vec![
            vec![("debian/control", TestFile::from(CONTROL))],
            vec![
                ("debian/control", TestFile::from(CONTROL)),
                ("src/lookup.c", TestFile::new("int a;\n")),
                // Right sentence, no version number.
                (
                    "src/vague.c",
                    TestFile::new("/* code produced by gperf version */\n"),
                ),
            ],
            // Quilt's `.pc/` is not the packaging's file.
            vec![
                ("debian/control", TestFile::from(CONTROL)),
                (".pc/gperf.c", TestFile::new(GPERF)),
            ],
            // A non-free package is not reported.
            vec![
                ("debian/control", TestFile::from(NON_FREE_CONTROL)),
                ("src/gperf.c", TestFile::new(GPERF)),
            ],
            // A hardlink is not read, as lintian's `full_text_check` does not.
            vec![
                ("debian/control", TestFile::from(CONTROL)),
                ("src/gperf.cpp", TestFile::new(GPERF).hardlink()),
            ],
        ];
        let fail = vec![vec![
            ("debian/control", TestFile::from(CONTROL)),
            ("src/gperf/gperf.c", TestFile::new(GPERF)),
        ]];
        SourceTreeTester::new(SourceContainsAutogeneratedGperfData, pass, fail).test_and_snapshot();
    }

    #[test]
    fn test_source_package() {
        let pass = vec![SourcePackageCase::from(vec![(
            "debian/control",
            TestFile::from(CONTROL),
        )])];
        let fail = vec![SourcePackageCase::from(vec![
            ("debian/control", TestFile::from(CONTROL)),
            ("src/gperf.c", TestFile::new(GPERF)),
        ])];
        SourcePackageTester::new(SourceContainsAutogeneratedGperfData, pass, fail)
            .test_and_snapshot();
    }
}
