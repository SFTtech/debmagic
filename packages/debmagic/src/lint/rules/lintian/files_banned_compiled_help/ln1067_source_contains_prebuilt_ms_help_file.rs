use std::path::PathBuf;

use crate::declare_rule;
use crate::lint::context::SourceContext;
use crate::lint::diagnostic::{Diagnostic, Location};
use crate::lint::file_tree::{Entry, EntryKind, FileTree};
use crate::lint::rule::SourceRule;

pub struct SourceContainsPrebuiltMsHelpFile;

declare_rule! {
    /// The Source tree or Source package contains a prebuilt Microsoft compiled
    /// HTML help file (`.chm`).
    ///
    /// Regular files and hardlinks whose name ends in `.chm` (any case) and
    /// whose content starts with the `ITSF` magic (`file(1)`'s "MS Windows
    /// HtmlHelp Data") are reported, unless the content contains `Halibut,`
    /// (a file generated by Halibut). Walks the packaging File tree (Source
    /// tree, or Source package Patched files); quilt `.pc/` is skipped. Extra
    /// is empty; the Entry path is the Location.
    SourceContainsPrebuiltMsHelpFile,
    code = "LN1067",
    tag = "source-contains-prebuilt-ms-help-file",
    default_selected = true,
    experimental = false,
}

impl SourceRule for SourceContainsPrebuiltMsHelpFile {
    fn run(&self, ctx: &mut SourceContext<'_>) {
        let Some(files) = ctx.files() else {
            return;
        };
        for path in prebuilt_help_paths(files) {
            // lintian's pointer is the whole hint here: the path is the extra.
            let extra = path.display().to_string();
            ctx.diagnostic(Diagnostic::error(extra).with_location(Location {
                path,
                line: None,
                column: None,
            }));
        }
    }
}

fn prebuilt_help_paths(files: &FileTree) -> Vec<PathBuf> {
    files
        .query()
        .kinds([EntryKind::RegularFile, EntryKind::Hardlink])
        .into_iter()
        .filter(|entry| !entry.path().starts_with(".pc") && is_prebuilt_help(files, entry))
        .map(|entry| entry.path().to_path_buf())
        .collect()
}

fn is_prebuilt_help(files: &FileTree, entry: &Entry) -> bool {
    let is_chm = entry
        .path()
        .extension()
        .is_some_and(|ext| ext.eq_ignore_ascii_case("chm"));
    if !is_chm {
        return false;
    }
    files
        .read(entry)
        .is_ok_and(|bytes| bytes.starts_with(b"ITSF") && !contains(&bytes, b"Halibut,"))
}

fn contains(haystack: &[u8], needle: &[u8]) -> bool {
    haystack
        .windows(needle.len())
        .any(|window| window == needle)
}

#[cfg(test)]
mod tests {
    use crate::lint::tester::{SourceTreeTester, TestCase, TestFile};

    use super::*;

    const CONTROL: &str = "Source: example\n\
         Maintainer: Example <ex@example.com>\n\
         Standards-Version: 4.7.2\n\
         \n\
         Package: example\n\
         Architecture: all\n\
         Description: example\n extra\n";

    fn chm() -> TestFile {
        TestFile::new("ITSF\x03\x00\x00\x00 compiled help")
    }

    fn with_control(files: Vec<(&str, TestFile)>) -> TestCase {
        let mut all = vec![("debian/control", TestFile::from(CONTROL))];
        all.extend(files);
        TestCase::from(all)
    }

    #[test]
    fn source() {
        let pass = vec![
            with_control(vec![]),
            // Not a .chm name.
            with_control(vec![("doc/help.hlp", chm())]),
            // Right name, not the ITSF magic.
            with_control(vec![("doc/fake.chm", TestFile::new("not a help file"))]),
            // Generated by Halibut.
            with_control(vec![(
                "doc/manual.chm",
                TestFile::new("ITSF Halibut, generated"),
            )]),
            // Quilt patch state is not the source.
            with_control(vec![(".pc/help.chm/help.chm", chm())]),
            // A symlink is not a file.
            with_control(vec![("doc/link.chm", TestFile::symlink("help.chm"))]),
        ];
        let fail = vec![
            with_control(vec![("doc/help.chm", chm())]),
            // Case-insensitive extension.
            with_control(vec![("doc/HELP.CHM", chm())]),
            // Hardlink to a help file.
            with_control(vec![
                ("doc/help.chm", chm()),
                ("doc/copy.chm", chm().hardlink_to("doc/help.chm")),
            ]),
            // Nested under debian/ too.
            with_control(vec![("debian/missing-sources/help.chm", chm())]),
        ];
        SourceTreeTester::new(SourceContainsPrebuiltMsHelpFile, pass, fail).test_and_snapshot();
    }
}
