use crate::declare_rule;
use crate::lint::context::SourceContext;
use crate::lint::diagnostic::{Diagnostic, Location};
use crate::lint::license_text::{self, TextFile};
use crate::lint::rule::{Severity, SourceRule};

pub struct SourceContainsAutogeneratedVisualCFile;

declare_rule! {
    /// A Patched file is C or C++ code that Microsoft Visual C++ generated:
    /// its text says `Microsoft Visual C++ generated`. A file that says it was
    /// generated `by freeze.py` is the exception. Reported at pedantic
    /// severity with an empty extra and the path as the Location, the pointer
    /// form lintian's `cruft` Check emits.
    ///
    /// The file's cleaned text is matched as lintian's `cruft` Check does: a
    /// keyword, the sentence, and the clause that is not followed by
    /// ` by freeze.py`. Skipped in a non-free Source package (see
    /// `license_text::is_non_free`), and paths under `.pc/` are skipped.
    ///
    /// Differs from lintian: the file is matched whole, not in 16 KiB
    /// sliding-window blocks, and the negative look-ahead of the regex is a
    /// check on each occurrence of the sentence (the Rust `regex` crate has no
    /// look-around).
    SourceContainsAutogeneratedVisualCFile,
    code = "LN1621",
    tag = "source-contains-autogenerated-visual-c++-file",
    default_selected = false,
    experimental = false,
}

const SENTENCE: &str = "microsoft visual c++ generated";
const FREEZE: &str = " by freeze.py";

/// lintian's `source-contains-autogenerated-visual-c++-file` table entry.
fn is_visual_cpp_generated(file: &TextFile) -> bool {
    ["microsoft", "visual", "generated"]
        .iter()
        .any(|keyword| file.lowercase.contains(keyword))
        && file
            .clean()
            .match_indices(SENTENCE)
            .any(|(at, _)| !file.clean()[at + SENTENCE.len()..].starts_with(FREEZE))
}

impl SourceRule for SourceContainsAutogeneratedVisualCFile {
    fn run(&self, ctx: &mut SourceContext<'_>) {
        if license_text::is_non_free(ctx) {
            return;
        }
        let texts = license_text::shared_text_files(ctx);
        let flagged: Vec<_> = texts
            .iter()
            .filter(|file| is_visual_cpp_generated(file))
            .map(|file| file.path.clone())
            .collect();
        for path in flagged {
            ctx.diagnostic(
                Diagnostic::warn("")
                    .with_severity(Severity::Pedantic)
                    .with_location(Location {
                        path,
                        line: None,
                        column: None,
                    }),
            );
        }
    }
}

#[cfg(test)]
mod tests {
    use crate::lint::tester::{SourcePackageCase, SourcePackageTester, SourceTreeTester, TestFile};

    use super::*;

    const CONTROL: &str = "Source: example\n\
         Maintainer: Example <ex@example.com>\n\
         Standards-Version: 4.7.2\n\
         \n\
         Package: example\n\
         Architecture: all\n\
         Description: example\n extra\n";

    const NON_FREE_CONTROL: &str = "Source: example\n\
         Section: non-free/libs\n\
         Maintainer: Example <ex@example.com>\n\
         Standards-Version: 4.7.2\n\
         \n\
         Package: example\n\
         Architecture: all\n\
         Description: example\n extra\n";

    const POSITIVE: &str = "// Microsoft Visual C++ generated file.\nint main() {}\n";

    #[test]
    fn test() {
        let pass = vec![
            vec![("debian/control", TestFile::from(CONTROL))],
            vec![
                ("debian/control", TestFile::from(CONTROL)),
                ("src/main.cpp", TestFile::new("int main() {}\n")),
                // Generated by freeze.py, which is the exception.
                (
                    "src/freeze.cpp",
                    TestFile::new("// Microsoft Visual C++ generated by freeze.py\n"),
                ),
            ],
            // Quilt's `.pc/` is not the packaging's file.
            vec![
                ("debian/control", TestFile::from(CONTROL)),
                (".pc/positive.cpp", TestFile::new(POSITIVE)),
            ],
            // A non-free package is not reported.
            vec![
                ("debian/control", TestFile::from(NON_FREE_CONTROL)),
                ("src/positive.cpp", TestFile::new(POSITIVE)),
            ],
            // A hardlink is not read, as lintian's `full_text_check` does not.
            vec![
                ("debian/control", TestFile::from(CONTROL)),
                ("src/positive.cpp", TestFile::new(POSITIVE).hardlink()),
            ],
        ];
        let fail = vec![
            vec![
                ("debian/control", TestFile::from(CONTROL)),
                ("src/visualc++/positive.cpp", TestFile::new(POSITIVE)),
            ],
            // Another occurrence without the exception still counts.
            vec![
                ("debian/control", TestFile::from(CONTROL)),
                (
                    "src/mixed.cpp",
                    TestFile::new(
                        "// Microsoft Visual C++ generated by freeze.py\n// Microsoft Visual C++ generated\n",
                    ),
                ),
            ],
        ];
        SourceTreeTester::new(SourceContainsAutogeneratedVisualCFile, pass, fail)
            .test_and_snapshot();
    }

    #[test]
    fn test_source_package() {
        let pass = vec![SourcePackageCase::from(vec![(
            "debian/control",
            TestFile::from(CONTROL),
        )])];
        let fail = vec![SourcePackageCase::from(vec![
            ("debian/control", TestFile::from(CONTROL)),
            ("src/positive.cpp", TestFile::new(POSITIVE)),
        ])];
        SourcePackageTester::new(SourceContainsAutogeneratedVisualCFile, pass, fail)
            .test_and_snapshot();
    }
}
