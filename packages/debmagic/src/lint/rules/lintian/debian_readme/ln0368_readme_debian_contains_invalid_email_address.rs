use std::sync::LazyLock;

use regex::Regex;

use crate::declare_rule;
use crate::lint::context::BinaryPackageContext;
use crate::lint::diagnostic::{Diagnostic, Location};
use crate::lint::rule::BinaryPackageRule;

use super::readme::readme_text;

pub struct ReadmeDebianContainsInvalidEmailAddress;

declare_rule! {
    /// `README.Debian` signs off with an e-mail address whose domain has no dot.
    ///
    /// The first readable `README.Debian` under `usr/share/doc/<package>/` is
    /// read whole. A debmake template boilerplate line wins and this Tag stays
    /// quiet. Otherwise the first line that starts with `-- ` and has an
    /// `<address>` whose domain has no dot is reported. Extra is that address.
    /// Location is the file, without a line.
    ReadmeDebianContainsInvalidEmailAddress,
    code = "LN0368",
    tag = "readme-debian-contains-invalid-email-address",
    default_selected = true,
    experimental = false,
}

static DEBMAKE_TEMPLATE: LazyLock<Regex> = LazyLock::new(|| {
    Regex::new(
        r"(?i)Comments regarding the Package|So far nothing to say|<possible notes regarding this package - if none, delete this file>|Automatically generated by debmake",
    )
    .expect("valid regex")
});

static SIGN_OFF: LazyLock<Regex> =
    LazyLock::new(|| Regex::new(r"(?m)^\s*-- [^<]*<([^> ]+.@[^>.]*)>").expect("valid regex"));

impl BinaryPackageRule for ReadmeDebianContainsInvalidEmailAddress {
    fn run(&self, ctx: &mut BinaryPackageContext<'_>) {
        let package = ctx.package_name().to_string();
        let found = {
            let Some(files) = ctx.data_files() else {
                return;
            };
            readme_text(files, &package)
                .and_then(|(path, text)| invalid_address(&text).map(|address| (path, address)))
        };
        let Some((path, address)) = found else {
            return;
        };
        ctx.diagnostic(Diagnostic::warn(address).with_location(Location {
            path,
            line: None,
            column: None,
        }));
    }
}

fn invalid_address(text: &str) -> Option<String> {
    if DEBMAKE_TEMPLATE.is_match(text) {
        return None;
    }
    SIGN_OFF
        .captures(text)
        .map(|captures| captures[1].to_string())
}

#[cfg(test)]
mod tests {
    use crate::lint::tester::{BinaryPackageCase, BinaryPackageTester, TestFile};

    use super::*;

    fn readme(package: &str, body: &str) -> BinaryPackageCase {
        BinaryPackageCase::from(vec![(
            format!("usr/share/doc/{package}/README.Debian"),
            TestFile::new(body),
        )])
        .package(package)
    }

    #[test]
    fn test() {
        let pass = vec![
            BinaryPackageCase::from(Vec::<(&str, TestFile)>::new()),
            readme(
                "example",
                "Notes.\n\n -- Jane <jane@example.com>  Mon, 1 Jan 2024\n",
            ),
            readme("example", "No sign-off at all.\n"),
            // A debmake template line makes the file quiet for this Tag.
            readme(
                "example",
                "Automatically generated by debmake\n\n -- Jane <jane@unknown>\n",
            ),
            // The address must be on a `-- ` line.
            readme("example", "Mail jane@unknown directly.\n"),
            BinaryPackageCase::from(vec![(
                "usr/share/doc/example/README.Debian",
                TestFile::symlink("missing"),
            )]),
        ];
        let fail = vec![
            readme(
                "example",
                "Notes.\n\n -- Jane <jane@unknown>  Mon, 1 Jan 2024\n",
            ),
            readme("example", "Notes.\n -- Jane <foo@bar>\n"),
            readme(
                "bad-email-format",
                "Notes.\n -- Jane <foo@unknown>\n -- Other <bar@example.com>\n",
            ),
        ];
        BinaryPackageTester::new(ReadmeDebianContainsInvalidEmailAddress, pass, fail)
            .test_and_snapshot();
    }
}
