use crate::declare_rule;
use crate::lint::context::BinaryPackageContext;
use crate::lint::diagnostic::{Diagnostic, Location};
use crate::lint::rule::BinaryPackageRule;

use super::readme::readme_text;

pub struct ReadmeDebianContainsDebmakeTemplate;

declare_rule! {
    /// `README.Debian` still contains a phrase from the deb-make or
    /// dh_make template.
    ///
    /// The first readable file of `README.Debian.gz`, `README.Debian`,
    /// `README.debian.gz`, and `README.debian` directly under
    /// `usr/share/doc/<package>/` is scanned, as in lintian's `open_readme`.
    /// Matches case-insensitively any of: `Comments regarding the Package`,
    /// `So far nothing to say`, `<possible notes regarding this package - if
    /// none, delete this file>`, `Automatically generated by debmake`. Reported
    /// once per file. Extra is empty. The Location is that file, with no line.
    /// Applies to deb, udeb, and ddeb.
    ReadmeDebianContainsDebmakeTemplate,
    code = "LN0893",
    tag = "readme-debian-contains-debmake-template",
    default_selected = true,
    experimental = false,
}

const TEMPLATE_PHRASES: [&str; 4] = [
    "Comments regarding the Package",
    "So far nothing to say",
    "<possible notes regarding this package - if none, delete this file>",
    "Automatically generated by debmake",
];

impl BinaryPackageRule for ReadmeDebianContainsDebmakeTemplate {
    fn run(&self, ctx: &mut BinaryPackageContext<'_>) {
        let package = ctx.package_name().to_string();
        let path = {
            let Some(files) = ctx.data_files() else {
                return;
            };
            let Some((path, text)) = readme_text(files, &package) else {
                return;
            };
            if !contains_template(&text) {
                return;
            }
            path
        };
        ctx.diagnostic(Diagnostic::warn("").with_location(Location {
            path,
            line: None,
            column: None,
        }));
    }
}

fn contains_template(text: &str) -> bool {
    let lowered = text.to_lowercase();
    TEMPLATE_PHRASES
        .iter()
        .any(|phrase| lowered.contains(&phrase.to_lowercase()))
}

#[cfg(test)]
mod tests {
    use crate::lint::tester::{BinaryPackageCase, BinaryPackageTester, TestFile};

    use super::*;

    fn readme(package: &str, name: &str, body: &str) -> BinaryPackageCase {
        BinaryPackageCase::from(vec![(
            format!("usr/share/doc/{package}/{name}"),
            TestFile::new(body),
        )])
        .package(package)
    }

    #[test]
    fn binary() {
        let pass = vec![
            BinaryPackageCase::from(Vec::<(&str, TestFile)>::new()),
            readme(
                "example",
                "README.Debian",
                "Real notes about the package.\n",
            ),
            // The gzip name comes first, so a clean gzip shadows a dirty plain file.
            BinaryPackageCase::from(vec![
                (
                    "usr/share/doc/example/README.Debian.gz",
                    TestFile::from_bytes(gzip(b"Real notes.\n")),
                ),
                (
                    "usr/share/doc/example/README.Debian",
                    TestFile::new("So far nothing to say\n"),
                ),
            ])
            .package("example"),
            // A symlink is not opened.
            BinaryPackageCase::from(vec![
                (
                    "usr/share/doc/example/README.Debian",
                    TestFile::symlink("other"),
                ),
                (
                    "usr/share/doc/example/other",
                    TestFile::new("So far nothing to say\n"),
                ),
            ])
            .package("example"),
        ];
        let fail = vec![
            readme(
                "example",
                "README.Debian",
                "Comments regarding the Package\n",
            ),
            readme("example", "README.Debian", "so far NOTHING TO SAY\n"),
            readme(
                "example",
                "README.Debian",
                "<possible notes regarding this package - if none, delete this file>\n",
            ),
            readme(
                "example",
                "README.debian",
                "Automatically generated by debmake\n",
            ),
            BinaryPackageCase::from(vec![(
                "usr/share/doc/example/README.Debian.gz",
                TestFile::from_bytes(gzip(b"Automatically generated by debmake\n")),
            )])
            .package("example"),
            // Non-UTF-8 bytes around the template still match.
            BinaryPackageCase::from(vec![(
                "usr/share/doc/example/README.Debian",
                TestFile::from_bytes(b"\xff So far nothing to say\n".to_vec()),
            )])
            .package("example"),
        ];
        BinaryPackageTester::new(ReadmeDebianContainsDebmakeTemplate, pass, fail)
            .test_and_snapshot();
    }

    fn gzip(body: &[u8]) -> Vec<u8> {
        use std::io::Write;
        let mut encoder = flate2::write::GzEncoder::new(Vec::new(), flate2::Compression::default());
        encoder.write_all(body).expect("gzip");
        encoder.finish().expect("gzip finish")
    }
}
