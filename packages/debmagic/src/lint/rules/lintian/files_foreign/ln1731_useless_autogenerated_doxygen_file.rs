use std::path::{Path, PathBuf};

use regex::Regex;

use crate::declare_rule;
use crate::lint::context::BinaryPackageContext;
use crate::lint::diagnostic::{Diagnostic, Location};
use crate::lint::file_tree::{Entry, FileTree};
use crate::lint::rule::{BinaryPackageRule, Severity};

pub struct UselessAutogeneratedDoxygenFile;

declare_rule! {
    /// A doxygen build cache file is shipped with the documentation.
    ///
    /// Walks Data files. An entry at `usr/share/doc/<package>/<dir>/<rest>.md5`,
    /// where `<rest>` is at least one character and may contain `/`, is
    /// reported when its directory also holds a `doxygen.png` entry of any
    /// kind. The `.md5` files are doxygen's incremental-build cache. The
    /// package name is this package's name, matched literally. Extra is empty;
    /// the Location is the `.md5` file. Udebs are checked too.
    UselessAutogeneratedDoxygenFile,
    code = "LN1731",
    tag = "useless-autogenerated-doxygen-file",
    default_selected = false,
    experimental = false,
}

impl BinaryPackageRule for UselessAutogeneratedDoxygenFile {
    fn run(&self, ctx: &mut BinaryPackageContext<'_>) {
        let package = ctx.package_name().to_string();
        let Some(files) = ctx.data_files() else {
            return;
        };
        let pattern = Regex::new(&format!(
            r"^usr/share/doc/{}/[^/]+/.+\.md5$",
            regex::escape(&package)
        ))
        .expect("valid regex");
        let hits: Vec<PathBuf> = files
            .entries()
            .iter()
            .filter(|entry| is_autogenerated_doxygen(files, &pattern, entry))
            .map(|entry| entry.path().to_path_buf())
            .collect();
        for path in hits {
            ctx.diagnostic(
                Diagnostic::warn("")
                    .with_severity(Severity::Info)
                    .with_location(Location {
                        path,
                        line: None,
                        column: None,
                    }),
            );
        }
    }
}

/// A `.md5` file under the package's doc directory whose directory has a
/// `doxygen.png`.
fn is_autogenerated_doxygen(files: &FileTree, pattern: &Regex, entry: &Entry) -> bool {
    let Some(path) = entry.path().to_str() else {
        return false;
    };
    if !pattern.is_match(path) {
        return false;
    }
    let Some(parent) = entry.path().parent() else {
        return false;
    };
    files.get(Path::join(parent, "doxygen.png")).is_some()
}

#[cfg(test)]
mod tests {
    use crate::lint::tester::{BinaryPackageCase, BinaryPackageTester, TestFile};

    use super::*;

    fn case(entries: Vec<(&str, TestFile)>) -> BinaryPackageCase {
        BinaryPackageCase::from(entries)
    }

    #[test]
    fn binary() {
        let pass = vec![
            case(vec![]),
            // No doxygen.png next to the cache file.
            case(vec![(
                "usr/share/doc/example/html/foo.md5",
                TestFile::new("x"),
            )]),
            // The cache file is not directly under the package's doc directory.
            case(vec![
                ("usr/share/doc/example/foo.md5", TestFile::new("x")),
                ("usr/share/doc/example/doxygen.png", TestFile::new("x")),
            ]),
            // Another package's doc directory.
            case(vec![
                ("usr/share/doc/other/html/foo.md5", TestFile::new("x")),
                ("usr/share/doc/other/html/doxygen.png", TestFile::new("x")),
            ]),
            // Not a .md5 file.
            case(vec![
                ("usr/share/doc/example/html/foo.txt", TestFile::new("x")),
                ("usr/share/doc/example/html/doxygen.png", TestFile::new("x")),
            ]),
        ];
        let fail = vec![
            case(vec![
                ("usr/share/doc/example/html/foo.md5", TestFile::new("x")),
                ("usr/share/doc/example/html/doxygen.png", TestFile::new("x")),
            ]),
            // Nested subdirectories count, and the doxygen.png may be a symlink.
            case(vec![
                ("usr/share/doc/example/html/sub/foo.md5", TestFile::new("x")),
                (
                    "usr/share/doc/example/html/sub/doxygen.png",
                    TestFile::symlink("x"),
                ),
            ]),
            // Udebs are checked too.
            case(vec![
                ("usr/share/doc/example/html/foo.md5", TestFile::new("x")),
                ("usr/share/doc/example/html/doxygen.png", TestFile::new("x")),
            ])
            .udeb(),
        ];
        BinaryPackageTester::new(UselessAutogeneratedDoxygenFile, pass, fail).test_and_snapshot();
    }
}
